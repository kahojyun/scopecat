"""Hardware-independent quantum domain building blocks for Scopecat.

This package owns logical circuit, pulse implementation, scheduling, and target
compiler contracts. It deliberately does not own laboratory wiring,
parameter values, concrete instrument artifacts, provider runtimes,
experiments, or analysis. Those concerns belong to a laboratory adapter that
depends on both ``scopecat`` and this package; core never imports quantum
vocabulary.

The transient lowering direction is unified gate/pulse authoring -> resolved
pulse implementation binding for logical operations -> either an expanded pulse
program or structured realtime pulse regions -> a target-owned compile request.
Each named pass establishes one immutable stage, and later stages rely on that
proof while checking only newly bound facts.
"""

